void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
    if (huart->Instance == USART2) {
        if (gps_index < GPS_BUFFER_SIZE - 1) {
            gps_buffer[gps_index++] = gps_rx_byte;
        }

        if (gps_rx_byte == '\n') {
            // Null-terminate the string
            if (gps_index > 1 && gps_buffer[gps_index-2] == '\r') {
                gps_buffer[gps_index-2] = '\0';
            } else {
                gps_buffer[gps_index-1] = '\0';
            }

            if (strstr((char *)gps_buffer, "GPRMC")) {
                if (parse_gprmc((char *)gps_buffer, &rmc)) {
                    printf("GPRMC Parsing Successful:\n");
                    printf("Time: %.2f (UTC)\n", rmc.time_utc);
                    printf("Status: %c\n", rmc.status);
                    printf("Position: %.5f %c, %.5f %c (Decimal Degrees)\n", 
                          rmc.latitude, rmc.lat_hemi, 
                          rmc.longitude, rmc.lon_hemi);
                    printf("Speed: %.3f (Knots)\n", rmc.speed_knots);
                } else {
                    printf("GPRMC Parsing Failed.\n");
                }
            } else if (strstr((char *)gps_buffer, "PGGA")) {
                if (parse_gpgga((char *)gps_buffer, &gga)) {
                    printf("GPGGA Parsing Successful:\n");
                    printf("Time: %.2f (UTC)\n", gga.time_utc);
                    printf("Position: %.5f %c, %.5f %c (Decimal Degrees)\n", 
                          gga.latitude, gga.lat_hemi, 
                          gga.longitude, gga.lon_hemi);
                    printf("Satellites: %d\n", gga.num_satellites);
                    printf("Altitude: %.1f %c (MSL)\n", gga.altitude_msl, gga.alt_unit);
                    printf("HDOP: %.2f\n", gga.hdop);
                } else {
                    printf("GPGGA Parsing Failed.\n");
                }
            }

            gps_index = 0;
        }

        HAL_UART_Receive_IT(&huart2, &gps_rx_byte, 1);
    }
}

